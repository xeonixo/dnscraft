// After `vite build`, writes build/sw.js with a precache list for the app shell.
import { readdir, stat, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const WEB = join(dirname(fileURLToPath(import.meta.url)), '..');
const BUILD = join(WEB, 'build');

async function walk(dir, out = []) {
	for (const name of await readdir(dir)) {
		const path = join(dir, name);
		if ((await stat(path)).isDirectory()) await walk(path, out);
		else out.push(path);
	}
	return out;
}

function urlPath(file) {
	const rel = relative(BUILD, file).split('\\').join('/');
	return `/${rel}`;
}

const version = createHash('sha256')
	.update(String(Date.now()))
	.update(process.env.SOURCE_DATE_EPOCH ?? '')
	.digest('hex')
	.slice(0, 12);

const files = await walk(BUILD);
const precache = files
	.filter((file) => {
		const url = urlPath(file);
		if (url === '/sw.js') return false;
		if (url.startsWith('/_app/immutable/')) return true;
		if (url === '/index.html') return true;
		if (url === '/manifest.webmanifest') return true;
		if (url.startsWith('/icons/')) return true;
		if (url === '/apple-touch-icon.png') return true;
		if (/\.woff2$/i.test(url)) return true;
		return false;
	})
	.map(urlPath)
	.sort();

const sw = `/* Generated by scripts/gen-sw.mjs — do not edit. */
const CACHE = 'dnscraft-shell-${version}';
const PRECACHE = ${JSON.stringify(precache, null, '\t')};

self.addEventListener('install', (event) => {
	event.waitUntil(
		caches
			.open(CACHE)
			.then((cache) => cache.addAll(PRECACHE))
			.then(() => self.skipWaiting()),
	);
});

self.addEventListener('activate', (event) => {
	event.waitUntil(
		caches
			.keys()
			.then((keys) => Promise.all(keys.filter((key) => key !== CACHE).map((key) => caches.delete(key))))
			.then(() => self.clients.claim()),
	);
});

self.addEventListener('fetch', (event) => {
	if (event.request.method !== 'GET') return;
	const url = new URL(event.request.url);
	if (url.origin !== self.location.origin) return;
	if (url.pathname.startsWith('/api/')) return;

	if (url.pathname.startsWith('/_app/immutable/')) {
		event.respondWith(
			caches.match(event.request).then(
				(cached) =>
					cached ??
					fetch(event.request).then((response) => {
						if (response.ok) {
							const copy = response.clone();
							void caches.open(CACHE).then((cache) => cache.put(event.request, copy));
						}
						return response;
					}),
			),
		);
		return;
	}

	if (event.request.mode === 'navigate') {
		event.respondWith(
			fetch(event.request).catch(() => caches.match('/index.html')),
		);
		return;
	}

	event.respondWith(
		caches.match(event.request).then((cached) => cached ?? fetch(event.request)),
	);
});
`;

await writeFile(join(BUILD, 'sw.js'), sw, 'utf8');
console.log(
	`Wrote build/sw.js (${precache.length} precache entries, cache dnscraft-shell-${version}).`,
);
